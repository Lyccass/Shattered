// Export the exact runtime relief renderer once, ahead of gameplay.
import {createCanvas,loadImage} from '@napi-rs/canvas';
import {createServer} from 'vite';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const server=await createServer({server:{middlewareMode:true},appType:'custom'});
globalThis.document={createElement:()=>createCanvas(1,1)};
try {
 const {ForestReliefRenderer}=await server.ssrLoadModule('/src/world/terrain/ForestReliefRenderer.ts');
 const {forestGroundBakeSignature}=await server.ssrLoadModule('/src/world/terrain/ForestGroundBakeSignature.ts');
 const manifest=JSON.parse(await readFile('data/worlds/the_wake/world.manifest.json','utf8'));
 const tiles=new Map();
 for(const ref of manifest.authoredChunks){
  const chunk=JSON.parse(await readFile(ref.path,'utf8'));
  chunk.terrain.tiles.forEach((row,y)=>row.forEach((value,x)=>{
   const def=chunk.terrainPalette[value];
   if(typeof def==='string')throw new Error('Bake requires explicit painted terrain');
   tiles.set(`${ref.chunkX*32+x},${ref.chunkY*32+y}`,def.tileId);
  }));
 }
 const sample=(x,y)=>tiles.get(`${x},${y}`)??null;
 const textures=new Map();
 for(const id of new Set(tiles.values())){
  const image=await loadImage(`public/assets/forest-painterly/${id}.png`);
  const c=createCanvas(256,128);c.getContext('2d').drawImage(image,0,0,256,128);textures.set(`terrain-${id}`,c);
 }
 for(const family of ['grass','dirt','stone','water','sand']){
  const key=`terrain-forest_${family}_1`;
  if(!textures.has(key))textures.set(key,await loadImage(`public/assets/forest-painterly/forest_${family}_1.png`));
 }
 textures.set('forest-grass-world-hd',await loadImage('public/assets/forest-painterly/grass-world-hd.png'));
 const scene={textures:{
  get:key=>({getSourceImage:()=>textures.get(key)}),
  createCanvas:(key,w,h)=>{const c=createCanvas(w,h);textures.set(key,c);return {context:c.getContext('2d'),refresh(){}};},
  remove:key=>textures.delete(key),
 }};
 const renderer=new ForestReliefRenderer(scene),entries=[];
 const output='public/assets/forest-painterly/ground';await mkdir(output,{recursive:true});
 // Same 8×8 render blocks and one-tile bleed as the runtime, at 2× resolution.
 for(let cy=0;cy<12;cy++)for(let cx=0;cx<12;cx++){
  const sx=Math.max(0,cx*8-1),sy=Math.max(0,cy*8-1),ex=Math.min(96,cx*8+9),ey=Math.min(96,cy*8+9);
  const bounds={drawStartX:sx,drawStartY:sy,drawEndX:ex,drawEndY:ey};
  const left=(sx-ey)*32-64,top=(sx+sy)*16-160;
  const width=(ex-sx+ey-sy)*32+128,height=(ex-sx+ey-sy)*16+256;
  const canvas=createCanvas(width*2,height*2),ctx=canvas.getContext('2d');ctx.scale(2,2);
  for(let diagonal=sx+sy;diagonal<=ex+ey-2;diagonal++)for(let x=sx;x<ex;x++){
   const y=diagonal-x;if(y<sy||y>=ey)continue;
   const id=sample(x,y),family=id.split('_')[1];
   const key=renderer.texture(x,y,family,`terrain-${id}`,[],sample),image=textures.get(key);
   ctx.drawImage(image,(x-y)*32-left-image.width/8,(x+y)*16+16-top-image.height/8,image.width/4,image.height/4);
   renderer.release(key);
  }
  const signature=forestGroundBakeSignature(bounds,sample),file=`${cx}_${cy}-${signature}.webp`;
  await writeFile(`${output}/${file}`,await canvas.encode('webp',95));
  entries.push({cx,cy,signature,file,width:width*2,height:height*2});
  if(cx===11)console.log(`Baked row ${cy+1}/12`);
 }
 await writeFile('src/world/terrain/generated/ForestGroundBakes.ts',`// Generated by npm run bake:ground. Do not edit.\nexport const FOREST_GROUND_BAKES = ${JSON.stringify(entries)} as const;\n`);
 console.log(`Exported ${entries.length} finished ground textures.`);
} finally {await server.close();}
